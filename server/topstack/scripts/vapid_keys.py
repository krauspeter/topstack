"""VAPID-Schlüssel für Web Push erzeugen (AP-8).

Auf dem Heimserver:  docker compose exec api python -m topstack.scripts.vapid_keys
Die beiden Zeilen kommen in ``infra/.env``. Den privaten Schlüssel nirgends sonst ablegen.
"""

import base64

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def generate() -> tuple[str, str]:
    """(öffentlich, privat) als base64url ohne Auffüllung, wie Browser und pywebpush sie wollen."""
    key = ec.generate_private_key(ec.SECP256R1())
    private = key.private_numbers().private_value.to_bytes(32, "big")
    public = key.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )
    return b64url(public), b64url(private)


def main() -> None:
    public, private = generate()
    print(f"VAPID_PUBLIC_KEY={public}")
    print(f"VAPID_PRIVATE_KEY={private}")


if __name__ == "__main__":
    main()
